    {
        [typeof(void)] = "void", [typeof(bool)] = "bool", [typeof(byte)] = "byte", [typeof(int)] = "int", [typeof(uint)] = "uint",
        [typeof(long)] = "long", [typeof(float)] = "float", [typeof(double)] = "double", [typeof(string)] = "string",
        [typeof(object)] = "object", [typeof(char)] = "char", [typeof(decimal)] = "decimal",
    };
}
